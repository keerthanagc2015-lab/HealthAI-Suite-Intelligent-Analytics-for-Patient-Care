# SIMPLE TESTS
# ---------------------------------------------------------------------

def run_safety_tests() -> bool:
    """
    Standalone validation tests for Module 17.14.
    """

    print("=" * 72)
    print("HEALTHAI - AGENT SAFETY TESTS")
    print("STEP 17.14")
    print("=" * 72)

    passed = 0
    total = 0

    # ---------------------------------------------------------------
    # TEST 1 - Empty query
    # ---------------------------------------------------------------

    total += 1

    result = apply_safety_gate(
        "",
        "safe_fallback",
        None,
    )

    if result["status"] == "fallback":
        print("TEST 1 - Empty query              : PASS")
        passed += 1
    else:
        print("TEST 1 - Empty query              : FAIL")

    # ---------------------------------------------------------------
    # TEST 2 - Unsupported tool
    # ---------------------------------------------------------------

    total += 1

    result = apply_safety_gate(
        "Tell me something unrelated.",
        "unknown_tool",
        {},
    )

    if result["status"] == "fallback":
        print("TEST 2 - Unsupported tool         : PASS")
        passed += 1
    else:
        print("TEST 2 - Unsupported tool         : FAIL")

    # ---------------------------------------------------------------
    # TEST 3 - Missing input
    # ---------------------------------------------------------------

    total += 1

    result = apply_safety_gate(
        "Predict diabetes risk.",
        "diabetes_prediction",
        {
            "status": "missing_input",
            "missing_fields": [
                "Age",
                "Blood_Glucose_mg_dL",
            ],
        },
    )

    if result["status"] == "missing_input":
        print("TEST 3 - Missing input            : PASS")
        passed += 1
    else:
        print("TEST 3 - Missing input            : FAIL")

    # ---------------------------------------------------------------
    # TEST 4 - Prediction disclaimer
    # ---------------------------------------------------------------

    total += 1

    result = apply_safety_gate(
        "Predict diabetes risk.",
        "diabetes_prediction",
        {
            "status": "success",
            "prediction": 1,
            "risk_label": "High diabetes risk",
        },
    )

    if (
        result["status"] == "success"
        and "clinical_disclaimer" in result
        and result["safety_checked"] is True
    ):
        print("TEST 4 - Prediction disclaimer   : PASS")
        passed += 1
    else:
        print("TEST 4 - Prediction disclaimer   : FAIL")

    # ---------------------------------------------------------------
    # TEST 5 - RAG abstention
    # ---------------------------------------------------------------

    total += 1

    result = apply_safety_gate(
        "What is an unsupported condition?",
        "medical_rag",
        {
            "status": "abstain",
            "retrieval_decision": "ABSTAIN",
            "evidence_count": 0,
        },
    )

    if result["status"] == "abstain":
        print("TEST 5 - RAG abstention           : PASS")
        passed += 1
    else:
        print("TEST 5 - RAG abstention           : FAIL")

    # ---------------------------------------------------------------
    # TEST 6 - RAG accepted
    # ---------------------------------------------------------------

    total += 1

    result = apply_safety_gate(
        "What is hypertension?",
        "medical_rag",
        {
            "status": "success",
            "retrieval_decision": "ACCEPT",
            "evidence_count": 2,
            "answer": "Grounded evidence answer.",
        },
    )

    if (
        result["status"] == "success"
        and result["safety_checked"] is True
    ):
        print("TEST 6 - RAG accepted              : PASS")
        passed += 1
    else:
        print("TEST 6 - RAG accepted              : FAIL")

    # ---------------------------------------------------------------
    # TEST 7 - Tool error
    # ---------------------------------------------------------------

    total += 1

    error_result = handle_execution_error(
        "xray_analysis",
        RuntimeError("test error"),
    )

    if error_result["status"] == "error":
        print("TEST 7 - Controlled tool error    : PASS")
        passed += 1
    else:
        print("TEST 7 - Controlled tool error    : FAIL")

    # ---------------------------------------------------------------
    # SUMMARY
    # ---------------------------------------------------------------

    print("-" * 72)
    print(f"Tests passed : {passed}/{total}")
    print(f"Accuracy     : {passed / total * 100:.2f}%")

    if passed == total:
        print("STEP 17.14 SAFETY TESTS PASSED")
        return True

    print("STEP 17.14 SAFETY TESTS FAILED")
    return False


